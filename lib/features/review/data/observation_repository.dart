import 'package:dio/dio.dart';

import '../../../core/constants/api_constants.dart';
import '../../../core/network/api_client.dart';
import '../../../shared/models/models.dart';

/// Live client for the `/v1/observations*` contract (submission, history,
/// manager review queue, approve/recount/reject) — see
/// URBANPETS_API_DOCUMENTATION.md. Wired directly to the real Laravel
/// endpoints as of Phase 11; UI state providers let failures propagate as
/// errors rather than falling back to mock data — see
/// lib/features/review/state/review_providers.dart and
/// lib/features/stock_count/state/stock_count_providers.dart.
class ObservationRepository {
  ObservationRepository({ApiClient? apiClient})
    : _apiClient = apiClient ?? ApiClient();

  final ApiClient _apiClient;

  /// Submits a blind stock-count or expiry-check observation.
  /// [idempotencyKey] MUST be a UUID v4 generated by the caller and reused
  /// verbatim on any automatic retry of the same submission attempt.
  Future<ObservationModel> submit({
    required String type,
    String? taskId,
    required String itemId,
    required String branchId,
    String? supplierId,
    String? batchNo,
    DateTime? expDateObserved,
    num? physicalQty,
    String? remarks,
    String? photoPath,
    required String idempotencyKey,
  }) async {
    final fields = <String, dynamic>{
      'type': type,
      'task_id': taskId,
      'item_id': itemId,
      'branch_id': branchId,
      if (supplierId != null) 'supplier_id': supplierId,
      'batch_no': batchNo,
      'exp_date_observed': expDateObserved?.toIso8601String(),
      'physical_qty': physicalQty,
      'remarks': remarks,
      'idempotency_key': idempotencyKey,
    };

    // Only switch to a multipart body when there's an actual photo to
    // upload — the real Laravel endpoint validates `photo` as `image|max:5120`
    // and expects a real uploaded file, not a path string. When there's no
    // photo, keep sending a plain JSON body (no need to force multipart).
    final dynamic body;
    if (photoPath != null && photoPath.isNotEmpty) {
      body = FormData.fromMap({
        ...fields,
        'photo': await MultipartFile.fromFile(
          photoPath,
          filename: photoPath.split(RegExp(r'[\\/]')).last,
        ),
      });
    } else {
      body = fields;
    }

    final response = await _apiClient.request(
      ApiConstants.observations,
      method: 'POST',
      data: body,
    );
    final data = response.data is Map && response.data['data'] != null
        ? response.data['data']
        : response.data;
    return ObservationModel.fromJson(data as Map<String, dynamic>);
  }

  Future<List<ObservationModel>> mine() async {
    final response = await _apiClient.request(ApiConstants.observationsMine);
    final list = _extractList(response.data);
    return list
        .map((e) => ObservationModel.fromJson(e as Map<String, dynamic>))
        .toList();
  }

  /// Manager/Owner only — includes system_qty_snapshot for variance display.
  Future<List<ObservationModel>> pending() async {
    final response = await _apiClient.request(ApiConstants.observationsPending);
    final list = _extractList(response.data);
    return list
        .map((e) => ObservationModel.fromJson(e as Map<String, dynamic>))
        .toList();
  }

  static String _ymd(DateTime d) =>
      '${d.year.toString().padLeft(4, '0')}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

  /// Query params shared by [history] and [myHistory]. Exposed for tests.
  static Map<String, dynamic> historyQuery({
    String? branchId,
    DateTime? dateFrom,
    DateTime? dateTo,
    String? type,
    String? status,
    int page = 1,
    int perPage = 20,
  }) => <String, dynamic>{
    if (branchId != null) 'branch_id': branchId,
    if (dateFrom != null) 'date_from': _ymd(dateFrom),
    if (dateTo != null) 'date_to': _ymd(dateTo),
    if (type != null) 'type': type,
    if (status != null) 'status': status,
    'page': page,
    'per_page': perPage,
  };

  /// Manager/Owner cross-staff audit view — `GET /v1/observations`. Distinct
  /// from [mine] (own-only) and [pending] (pending-only): any status, any
  /// submitter in the caller's accessible branch(es), filterable by
  /// branch/date-range/type/status, paginated. Includes
  /// system_qty_snapshot/variance and item/branch/submitter names. Backs the
  /// reviewer variant of the "History & Audit" screen. The server returns
  /// 403 for a Staff caller.
  Future<PagedResult<ObservationModel>> history({
    String? branchId,
    DateTime? dateFrom,
    DateTime? dateTo,
    String? type,
    String? status,
    int page = 1,
    int perPage = 20,
  }) async {
    final response = await _apiClient.request(
      ApiConstants.observations,
      queryParameters: historyQuery(
        branchId: branchId,
        dateFrom: dateFrom,
        dateTo: dateTo,
        type: type,
        status: status,
        page: page,
        perPage: perPage,
      ),
    );
    return PagedResult.fromLaravel(response.data, ObservationModel.fromJson);
  }

  /// The caller's OWN submissions — `GET /v1/observations/mine` — with the
  /// same filters as [history]. Scoped to `submitted_by = me` on the server
  /// (no parameter can widen it) and always the blind shape: no
  /// system_qty_snapshot / variance. Backs the Staff variant of the
  /// "History & Audit" screen.
  Future<PagedResult<ObservationModel>> myHistory({
    String? branchId,
    DateTime? dateFrom,
    DateTime? dateTo,
    String? type,
    String? status,
    int page = 1,
    int perPage = 20,
  }) async {
    final response = await _apiClient.request(
      ApiConstants.observationsMine,
      queryParameters: historyQuery(
        branchId: branchId,
        dateFrom: dateFrom,
        dateTo: dateTo,
        type: type,
        status: status,
        page: page,
        perPage: perPage,
      ),
    );
    return PagedResult.fromLaravel(response.data, ObservationModel.fromJson);
  }

  /// Full detail for one observation, including the `recounts` chain and
  /// `parent_observation` — the only endpoint that returns them (list
  /// endpoints never embed the chain). Used by [ObservationDetailScreen] to
  /// enrich whatever row model it was opened with.
  Future<ObservationModel> show(String id) async {
    final response = await _apiClient.request(ApiConstants.observationDetail(id));
    final data = response.data is Map && response.data['data'] != null
        ? response.data['data']
        : response.data;
    return ObservationModel.fromJson(data as Map<String, dynamic>);
  }

  /// Raw bytes of the uploaded evidence photo — Manager/Owner only on the
  /// server (same branch-scoping as approve/reject). Callers must only
  /// invoke this when [ObservationModel.photoPath] is non-null.
  Future<List<int>> photoBytes(String id) async {
    final response = await _apiClient.request(
      ApiConstants.observationPhoto(id),
      responseType: ResponseType.bytes,
    );
    return response.data as List<int>;
  }

  /// [approvedQty] is required for a `stock_count` approval (the server
  /// computes the actual ledger adjustment from it) and must be omitted for
  /// an `expiry_check` approval — the server rejects/ignores stock-quantity
  /// fields there by business rule (an expiry check review never changes
  /// stock), so it is sent only when provided.
  Future<ObservationModel> approve(
    String id, {
    num? approvedQty,
    String? remarks,
  }) async {
    final response = await _apiClient.request(
      ApiConstants.observationApprove(id),
      method: 'POST',
      data: {
        if (approvedQty != null) 'approved_qty': approvedQty,
        'remarks': remarks,
      },
    );
    final data = response.data is Map && response.data['data'] != null
        ? response.data['data']
        : response.data;
    return ObservationModel.fromJson(data as Map<String, dynamic>);
  }

  Future<ObservationModel> requestRecount(
    String id, {
    required String remarks,
  }) async {
    final response = await _apiClient.request(
      ApiConstants.observationRequestRecount(id),
      method: 'POST',
      data: {'remarks': remarks},
    );
    final data = response.data is Map && response.data['data'] != null
        ? response.data['data']
        : response.data;
    return ObservationModel.fromJson(data as Map<String, dynamic>);
  }

  Future<ObservationModel> reject(String id, {required String remarks}) async {
    final response = await _apiClient.request(
      ApiConstants.observationReject(id),
      method: 'POST',
      data: {'remarks': remarks},
    );
    final data = response.data is Map && response.data['data'] != null
        ? response.data['data']
        : response.data;
    return ObservationModel.fromJson(data as Map<String, dynamic>);
  }
}

/// The API always wraps list responses as `{"data": [...]}`; `response.data`
/// is therefore a `Map`, never a bare `List`. Checking the runtime type with
/// `is` (not `as`, which throws on a type mismatch instead of falling
/// through) avoids a `_Map is not a subtype of List` crash.
List<dynamic> _extractList(dynamic raw) {
  if (raw is List) return raw;
  if (raw is Map && raw['data'] is List) return raw['data'] as List;
  return const [];
}
